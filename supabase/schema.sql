-- Run this in your Supabase Project's SQL Editor

-- 1. Create complaints table
create table if not exists complaints (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  category text not null,
  location text not null,
  priority text default 'low', -- 'high', 'medium', 'low'
  status text default 'Submitted', -- 'Submitted', 'Under Review', 'Action in Progress', 'Resolved'
  image text,
  support_count integer default 0,
  dont_support_count integer default 0,
  citizen_id text not null, -- Persistent browser-generated ID for "My Complaints"
  
  -- Government resolution fields
  action_taken text,
  resolution_details text,
  expected_resolution_date date,
  resolution_date date,
  
  -- Citizen feedback fields (for resolved complaints)
  feedback_rating integer, -- 1 to 5 rating
  feedback_comment text,
  feedback_submitted_at timestamptz,

  created_at timestamptz default now()
);

-- 2. Row Level Security (RLS) policies
alter table complaints enable row level security;

-- Drop existing policies if re-running
drop policy if exists "Allow public read" on complaints;
drop policy if exists "Allow complaint submission" on complaints;
drop policy if exists "Allow citizen feedback update" on complaints;
drop policy if exists "Allow government update" on complaints;

-- Public can read all complaints
create policy "Allow public read" on complaints
  for select using (true);

-- Anyone can submit a complaint (requires citizen_id to be populated)
create policy "Allow complaint submission" on complaints
  for insert with check (citizen_id is not null and length(citizen_id) > 0);

-- Citizens can update their own complaint (e.g. submit feedback after resolution)
create policy "Allow citizen feedback update" on complaints
  for update using (
    citizen_id = coalesce(current_setting('request.headers', true)::json->>'x-citizen-id', '')
  );

-- Government updates via role header or internal server calls
create policy "Allow government update" on complaints
  for update using (
    coalesce(current_setting('request.headers', true)::json->>'x-darpan-role', '') = 'government'
  );

